import JSZip from 'jszip';
import type { Project } from '../../types/project';
import { generatePreviewHtml } from './htmlExporter';

/**
 * Clean up editor-specific attributes before producing production-ready HTML
 */
function cleanEditorArtifacts(html: string): string {
  return html
    .replace(/\s*data-vds-[a-z0-9-]+(?:="[^"]*")?/gi, '')
    .replace(/\s*contenteditable="[^"]*"/gi, '')
    .replace(/<style\b[^>]*id="vds-editor-style"[^>]*>[\s\S]*?<\/style>/gi, '')
    .replace(/<style\b[^>]*id="vibe-sticky-guard"[^>]*>[\s\S]*?<\/style>/gi, '');
}

/**
 * Helper to fetch an image or convert a base64 data-URL into a Blob
 */
async function fetchImageBlob(src: string): Promise<{ blob: Blob; ext: string } | null> {
  try {
    if (src.startsWith('data:image/')) {
      const match = src.match(/^data:image\/([a-zA-Z0-9+]+);base64,(.+)$/);
      if (match) {
        const rawExt = match[1].toLowerCase().replace('svg+xml', 'svg');
        const byteCharacters = atob(match[2]);
        const byteNumbers = new Array(byteCharacters.length);
        for (let i = 0; i < byteCharacters.length; i++) {
          byteNumbers[i] = byteCharacters.charCodeAt(i);
        }
        const byteArray = new Uint8Array(byteNumbers);
        return {
          blob: new Blob([byteArray], { type: `image/${rawExt}` }),
          ext: rawExt === 'jpeg' ? 'jpg' : rawExt,
        };
      }
    }

    // Try fetching external image (with CORS mode)
    const res = await fetch(src, { mode: 'cors' });
    if (!res.ok) return null;
    const blob = await res.blob();
    const contentType = blob.type || '';
    let ext = 'jpg';
    if (contentType.includes('png')) ext = 'png';
    else if (contentType.includes('svg')) ext = 'svg';
    else if (contentType.includes('webp')) ext = 'webp';
    else if (contentType.includes('gif')) ext = 'gif';
    else if (src.includes('.')) {
      const potential = src.split('?')[0].split('.').pop()?.toLowerCase();
      if (potential && ['png', 'jpg', 'jpeg', 'svg', 'webp', 'gif'].includes(potential)) {
        ext = potential === 'jpeg' ? 'jpg' : potential;
      }
    }
    return { blob, ext };
  } catch {
    // If CORS fails or network fails, keep original link intact
    return null;
  }
}

export interface ExportZipProgress {
  status: string;
  percent: number;
}

/**
 * Exports the entire project as a clean production zip:
 * - index.html (with local asset links)
 * - styles/style.css
 * - js/main.js
 * - photos/ (all logos, pictures, and graphics extracted and downloaded)
 */
export async function exportProjectToZip(
  project: Project,
  onProgress?: (progress: ExportZipProgress) => void
): Promise<Blob> {
  const zip = new JSZip();
  onProgress?.({ status: 'Preparing HTML & styles...', percent: 10 });

  const rawHtml = generatePreviewHtml(project);
  const parser = new DOMParser();
  const doc = parser.parseFromString(rawHtml, 'text/html');

  // Create subfolders in zip
  const photosFolder = zip.folder('photos');
  const cssFolder = zip.folder('styles');
  const jsFolder = zip.folder('js');

  // 1. Extract embedded CSS into styles/style.css
  const styles: string[] = [];
  doc.querySelectorAll('style').forEach((styleEl) => {
    if (styleEl.id !== 'vds-editor-style' && styleEl.id !== 'vibe-sticky-guard') {
      styles.push(styleEl.textContent || '');
    }
    styleEl.remove();
  });

  const combinedCss = styles.join('\n\n').trim();
  if (combinedCss) {
    cssFolder?.file('style.css', combinedCss);
    const linkEl = doc.createElement('link');
    linkEl.rel = 'stylesheet';
    linkEl.href = 'styles/style.css';
    doc.head.appendChild(linkEl);
  }

  // 2. Extract scripts or add starter JS into js/main.js
  const scripts: string[] = [];
  doc.querySelectorAll('script').forEach((scriptEl) => {
    if (scriptEl.textContent && !scriptEl.src) {
      scripts.push(scriptEl.textContent);
      scriptEl.remove();
    }
  });

  const mainJsContent = scripts.length > 0
    ? scripts.join('\n\n')
    : `// Generated by Vibe Design Studio\nconsole.log('Site initialized successfully.');\n`;
  jsFolder?.file('main.js', mainJsContent);

  const scriptTag = doc.createElement('script');
  scriptTag.src = 'js/main.js';
  doc.body.appendChild(scriptTag);

  // 3. Find and extract all pictures & logos into photos/ folder
  const imageElements = Array.from(doc.querySelectorAll('img')) as HTMLImageElement[];
  const backgroundElements = Array.from(doc.querySelectorAll('*')).filter((el) => {
    const bg = (el as HTMLElement).style?.backgroundImage;
    return bg && bg.includes('url(');
  }) as HTMLElement[];

  const totalImages = imageElements.length + backgroundElements.length;
  let processedCount = 0;
  const imageSrcMap = new Map<string, string>();

  // Process <img> tags
  for (let i = 0; i < imageElements.length; i++) {
    const img = imageElements[i];
    const src = img.getAttribute('src');
    if (!src || src.startsWith('#')) continue;

    onProgress?.({
      status: `Downloading photo ${i + 1} of ${imageElements.length}...`,
      percent: Math.round(15 + ((i + 1) / (totalImages || 1)) * 60),
    });

    if (imageSrcMap.has(src)) {
      img.setAttribute('src', imageSrcMap.get(src)!);
      continue;
    }

    const downloaded = await fetchImageBlob(src);
    if (downloaded && photosFolder) {
      const filename = `photo-${i + 1}.${downloaded.ext}`;
      photosFolder.file(filename, downloaded.blob);
      const relativePath = `photos/${filename}`;
      imageSrcMap.set(src, relativePath);
      img.setAttribute('src', relativePath);
    }
    processedCount++;
  }

  // Process CSS background-image elements
  for (let i = 0; i < backgroundElements.length; i++) {
    const el = backgroundElements[i];
    const bgStyle = el.style.backgroundImage;
    const urlMatch = bgStyle.match(/url\(['"]?(.*?)['"]?\)/);
    if (!urlMatch || !urlMatch[1]) continue;

    const bgSrc = urlMatch[1];
    if (imageSrcMap.has(bgSrc)) {
      el.style.backgroundImage = `url("${imageSrcMap.get(bgSrc)}")`;
      continue;
    }

    const downloaded = await fetchImageBlob(bgSrc);
    if (downloaded && photosFolder) {
      const filename = `photo-bg-${i + 1}.${downloaded.ext}`;
      photosFolder.file(filename, downloaded.blob);
      const relativePath = `photos/${filename}`;
      imageSrcMap.set(bgSrc, relativePath);
      el.style.backgroundImage = `url("${relativePath}")`;
    }
  }

  // Remove any remaining editor artifacts and write index.html
  onProgress?.({ status: 'Packaging ZIP file...', percent: 85 });
  const finalHtml = cleanEditorArtifacts('<!DOCTYPE html>\n' + doc.documentElement.outerHTML);
  zip.file('index.html', finalHtml);

  // Add README with instructions
  zip.file(
    'README.md',
    `# ${project.name}

Exported from **Vibe Design Studio**.

## Folder Structure
- \`index.html\` - The main responsive HTML file
- \`styles/style.css\` - Extracted stylesheets and design tokens
- \`js/main.js\` - JavaScript logic and interactions
- \`photos/\` - All downloaded images, logos, and graphics

## How to Run
Simply open \`index.html\` in any web browser, or upload these files directly to any static host (Netlify, Vercel, GitHub Pages, or cPanel/Apache/Nginx).
`
  );

  onProgress?.({ status: 'Generating ZIP archive...', percent: 95 });
  const zipBlob = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  });

  onProgress?.({ status: 'Done!', percent: 100 });
  return zipBlob;
}
